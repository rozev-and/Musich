import { create } from 'zustand'

/**
 * Живая позиция трека — отдельно от главного стора. Она меняется 4 раза в секунду, и в главном сторе на каждое
 * изменение прогонялись селекторы всех подписчиков (сотни строк треков). Здесь её слушают только полоска, время
 * и текст песни; в главном сторе позиция обновляется редко (смена трека, перемотка, раз в несколько секунд — для «продолжить»)
 */
export const usePos = create<{ position: number }>(() => ({ position: 0 }))
export const livePosition = () => usePos.getState().position

/**
 * Прогресс загрузки и отправки, id → проценты — тоже отдельно: раньше каждое обновление пересоздавало весь список
 * треков (фильтры, сортировки, умные плейлисты пересчитывались до 9 раз в секунду). Список треков меняется только
 * в начале и конце загрузки, а проценты слушают только строки и полоски, которые их показывают
 */
export const useProgress = create<Record<string, number | undefined>>(() => ({}))

/**
 * Трек грузится: нажали «играть», а звука ещё нет (сеть, сервер пережимает). Кнопка показывает кольцо загрузки.
 * Отдельно от главного стора — меняется часто, слушают только кнопки воспроизведения
 */
export const useBuffering = create<{ buffering: boolean }>(() => ({ buffering: false }))
